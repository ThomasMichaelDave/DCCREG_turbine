from scipy.linalg import expm as _expm

H_STEP = 5e-9              # expm step (ring 1.38 us, stray modes ~0.3 us periods)            [ME]
N_RAMP = 25                # piecewise-constant sub-steps across the 0.5 us arming ramp          [ME]


def mode_at(segs, t):
    m = None
    for a, b, mm, e in segs:
        if a <= t < b:
            m = mm
    return m


class ChainEngine:
    def __init__(self, res, t0):
        d, m, cfg = res["d"], res["meta"], res["cfg"]
        self.nodes = m["nodes"]; self.ix = {n: k for k, n in enumerate(self.nodes)}; N = len(self.nodes)
        K = np.zeros((N, N))
        def addc(a, b, C):
            ia, ib = self.ix.get(a), self.ix.get(b)
            if ia is not None: K[ia, ia] += C
            if ib is not None: K[ib, ib] += C
            if ia is not None and ib is not None: K[ia, ib] -= C; K[ib, ia] -= C
        for nm, a, b, C in m["caps"]:
            addc(a, b, C)
        for nm, a, b, kind in m["varcaps"]:
            addc(a, b, float(a1._c_of_t(kind, np.array([t0]))[0]))
        self.K = K; self.Ki = np.linalg.inv(K); self.N = N
        self.inds = [x for x in m["inds"] if x[3] > 0]
        Rm = dict(m.get("motor_r", []))
        self.R = np.array([cfg.rlx if nm in ("Lx3", "Lx4") else Rm.get(nm, 0.0) for nm, a, b, L in self.inds])
        self.L = np.array([x[3] for x in self.inds])
        self.gaps = m["gaps"]
        Bg = np.zeros((N, len(self.gaps))); Bl = np.zeros((N, len(self.inds)))
        for k, (g, a, b) in enumerate(self.gaps):
            if a in self.ix: Bg[self.ix[a], k] += 1
            if b in self.ix: Bg[self.ix[b], k] -= 1
        for k, (nm, a, b, L) in enumerate(self.inds):
            if a in self.ix: Bl[self.ix[a], k] += 1
            if b in self.ix: Bl[self.ix[b], k] -= 1
        self.Bg, self.Bl = Bg, Bl
        t = d["time"]
        V0 = np.array([np.interp(t0, t, d[f"v({n})"]) for n in self.nodes])
        I0 = np.array([np.interp(t0, t, d[f"i(l_{nm.lower()})"]) for nm, a, b, L in self.inds])
        self.x0 = np.concatenate([V0, I0])
        self._cache = {}

    def A(self, gvec):
        key = tuple(np.round(gvec, 12))
        if key not in self._cache:
            N, m = self.N, len(self.inds)
            A = np.zeros((N + m, N + m))
            A[:N, :N] = -self.Ki @ (self.Bg @ np.diag(gvec) @ self.Bg.T)
            A[:N, N:] = -self.Ki @ self.Bl
            A[N:, :N] = (self.Bl.T) / self.L[:, None]
            A[N:, N:] = -np.diag(self.R / self.L)
            self._cache[key] = (A, {})
        return self._cache[key]

    def step(self, gvec, x, h):
        A, E = self.A(gvec)
        hk = round(h, 15)
        if hk not in E:
            E[hk] = _expm(A * h)
        return E[hk] @ x

    def vgap(self, x, k):
        return float(self.Bg[:, k] @ x[:self.N])


def resolve_chain(res, sched, g, t_ign, t_end, model, h, t_rec, holdoff=HOLDOFF, span=None):
    """Run the M-SR (or M-RD) state machine for load gap g from t_ign with other gaps held at their
    scheduled modes. Returns (segments for g on [t_ign, t_end], event records)."""
    E = ChainEngine(res, t_ign)
    kg = [x[0] for x in E.gaps].index(g)
    RON, ROFF = a1.GAP_RON, a1.GAP_ROFF
    others = {k: mode_at(sched[x[0]], t_ign + 1e-9) for k, x in enumerate(E.gaps) if k != kg}
    x = E.x0.copy(); t = t_ign
    segs = []; recs = []
    state = "arc"; Vf = E.vgap(x, kg); p1 = None; pk = 0.0; tpk = t; hsgn = 0.0
    ev = dict(t_ign=t_ign, Vf=Vf, p1=None, ext=None, reignite=None, trv=None)
    seg_start, seg_edge = t_ign, EDGE_IGN
    t_ext = None; t_h_end = None; trv_pk = 0.0
    tstop = t_end if span is None else min(t_end, t_ign + span)
    closing = False                 # window end while arcing: extinguish at the NEXT current zero
    ramp_end = t_ign + EDGE_IGN

    def gvec_at(xx, tt):
        gv = np.full(len(E.gaps), 1.0 / ROFF)
        for k, mm in others.items():
            v = E.vgap(xx, k)
            if mm == "bi" or (mm == "f" and v > 0) or (mm == "r" and v < 0):
                gv[k] = 1.0 / RON
        if state == "arc":
            frac = 1.0 if tt >= ramp_end else max(0.0, (tt - t_ign) / EDGE_IGN)
            gv[kg] = max(1.0 / ROFF, frac / RON)
        return gv
    first = True
    while t < tstop or closing:
        if state == "arc" and t < ramp_end:
            hh = min(EDGE_IGN / N_RAMP, ramp_end - t)
            gv = gvec_at(x, t + 0.5 * hh)
        else:
            hh = H_STEP if closing else min(H_STEP, tstop - t)
            gv = gvec_at(x, t)
        x1 = E.step(gv, x, hh)
        v0, v1 = E.vgap(x, kg), E.vgap(x1, kg)
        # other rectifiers changing conduction inside the step -> bisect to the sign change
        def other_flip(xa, xb):
            for k, mm in others.items():
                if mm in ("f", "r") and np.sign(E.vgap(xa, k)) != np.sign(E.vgap(xb, k)):
                    return True
            return False
        trig = other_flip(x, x1)
        if state == "arc":
            i0, i1 = v0 * gv[kg], v1 * gv[kg]
            zero = (not first) and np.sign(v0) != np.sign(v1) and v0 != 0
            trig = trig or zero
        elif state == "hold":
            rho = lambda tt: 1.0 if t_rec <= 0 else 1.0 - math.exp(-(tt - t_ext) / t_rec)
            thr1 = abs(v1) - rho(t + hh) * abs(Vf)
            re = (t + hh > t_ext + 2 * EDGE_SW) and thr1 > 0
            trig = trig or re or (t + hh >= t_h_end)
        if trig:
            lo, hi = 0.0, hh
            for _ in range(50):
                mid = 0.5 * (lo + hi); xm = E.step(gv, x, mid); vm = E.vgap(xm, kg)
                c = other_flip(x, xm)
                if state == "arc":
                    c = c or (np.sign(v0) != np.sign(vm) and v0 != 0 and not first)
                elif state == "hold":
                    c = c or ((t + mid > t_ext + 2 * EDGE_SW) and abs(vm) - rho(t + mid) * abs(Vf) > 0) \
                        or (t + mid >= t_h_end)
                if c:
                    hi = mid
                else:
                    lo = mid
            hh = hi; x1 = E.step(gv, x, hh); v1 = E.vgap(x1, kg)
        tn = t + hh
        if state == "arc":
            iabs = abs(v1) * gv[kg]                          # actual (ramped) conductance
            ev["p1_full"] = max(ev.get("p1_full") or 0.0, iabs) if p1 is None else ev.get("p1_full")
            if p1 is None and tn < seg_start + T_SPIKE:
                iabs = 0.0                                   # stray-dump spike excluded (T_SPIKE)
            if iabs > pk:
                pk, tpk, hsgn = iabs, tn, np.sign(v1)
            first = False
            if closing and trig and np.sign(v0) != np.sign(v1) and v0 != 0:
                segs.append((t_end, tn, "f" if np.sign(v0) > 0 else "r", EDGE_SW))
                ev["ext"] = tn; ev["i_at_ext"] = 0.0; ev["window_end"] = True
                recs.append(ev); return segs, recs
            if trig and np.sign(v0) != np.sign(v1) and v0 != 0 and not closing:
                # a half-cycle closed at tn with peak pk and sign hsgn
                if p1 is None:
                    p1 = pk; ev["p1"] = p1
                if pk < h * p1:
                    mode_x = "f" if hsgn > 0 else "r"
                    # hand-off bi -> rectifier inside the same-sign half-cycle, never inside the
                    # arming ramp (it would cut the ramp short); seamless by construction
                    tsw = min(max(tpk, ramp_end + EDGE_SW), tn - 2 * EDGE_SW)
                    segs.append((seg_start, tsw, "bi", seg_edge))
                    segs.append((tsw, tn, mode_x, EDGE_SW))
                    tpk = tsw
                    ev.update(ext=tn, sgn_ext=hsgn, i_at_ext=0.0)
                    t_ext = tn
                    if model == "RD" or holdoff <= 0:
                        if mode_x == "f":
                            segs[-1] = (tpk, t_end, "f", EDGE_SW)
                        else:
                            segs.append((tn, t_end, "f", EDGE_SW))
                        recs.append(ev); return segs, recs
                    state = "hold"; t_h_end = min(t_ext + holdoff, t_end); trv_pk = 0.0
                    seg_start = tn
                pk = 0.0
        elif state == "hold":
            trv_pk = max(trv_pk, abs(v1))
            if tn >= t_h_end - 1e-15:
                segs.append((seg_start, t_h_end, "off", EDGE_SW))
                ev.update(reignite=None, trv=trv_pk / abs(Vf))
                recs.append(ev)
                if t_h_end < t_end:
                    segs.append((t_h_end, t_end, "f", EDGE_SW))
                return segs, recs
            if trig and (tn > t_ext + 2 * EDGE_SW) and abs(v1) - rho(tn) * abs(Vf) >= -1e-9 * abs(Vf):
                segs.append((seg_start, tn, "off", EDGE_SW))
                ev.update(reignite=tn, trv=trv_pk / abs(Vf)); recs.append(ev)
                state = "arc"; Vf = v1; p1 = None; pk = 0.0; first = True
                ev = dict(t_ign=tn, Vf=Vf, p1=None, ext=None, reignite=None, trv=None)
                seg_start, seg_edge = tn, EDGE_SW; ramp_end = tn   # re-ignition: no arming ramp
        x, t = x1, tn
        if state == "arc" and not closing and t >= tstop and span is None:
            # the window closes on a live arc: the electrodes part, the arc goes out at its next
            # natural current zero (rectifier of the current's sign from t_end) -> no chop (H2)
            segs.append((seg_start, t_end, "bi", seg_edge)); closing = True
            if t - t_ign > 3e-3:
                break
    if closing:
        recs.append(ev); return segs, recs
    # span reached while arcing or holding
    if state == "arc":
        segs.append((seg_start, t_end, "bi", seg_edge)); ev["i_at_end"] = abs(E.vgap(x, kg)) / RON
    else:
        segs.append((seg_start, t_end, "off", EDGE_SW))
    recs.append(ev)
    return segs, recs


def fixed_point_sr(cfg, model, h, t_rec, holdoff=HOLDOFF, maxit=6, tol_ns=30):
    """Machine-level fixed point with the chain engine resolving each load event."""
    sched = sched_static(cfg, "f")
    for it in range(maxit):
        cfg.name = re.sub(r"_it\d+$", "", cfg.name) + f"_it{it}"
        r = run(cfg, sched)
        new = dict(sched); events = {}
        tend = r["d"]["time"][-1]
        for g in LOAD:
            segs = []; recs = []
            for (t0, t1) in windows_abs(g, cfg.ncyc):
                if t0 >= tend:
                    break
                s_, r_ = resolve_chain(r, sched, g, t0, t1, model, h, t_rec, holdoff)
                segs += s_; recs += r_
            new[g] = segs; events[g] = recs
        same = _close(new, sched, tol_ns)
        if same:
            r["iters"] = it + 1; r["events"] = events; r["converged"] = True
            return r
        _rm_raw(cfg.name) if it < maxit - 1 else None
        sched = new
    r["iters"] = maxit; r["events"] = events; r["converged"] = False
    return r


