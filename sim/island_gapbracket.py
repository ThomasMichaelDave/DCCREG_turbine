BKPT_OFFSET = 2e-9          # station edges offset 2 ns: never coincident (to ~1e-12) with the
                            # periodic Cx/clock PWL breakpoints ngspice computes itself [ME]


def windows_abs(g, ncyc):
    a, b = a1.WINDOWS[g]
    return [(c * T + a * DEG + BKPT_OFFSET, c * T + b * DEG + BKPT_OFFSET) for c in range(ncyc)]


def base_mode(g, bracket):
    if g in a1.RAIL_GAPS:
        return "f"
    if g in a1.ISLAND_GAPS:
        return "bi" if bracket == "a" else "f"
    return "f"                                      # load: Pass A one-way


def sched_static(cfg, load_mode="f", d1=None):
    """Static schedules: every gap its Pass A mode; load gaps `load_mode` over the window.
    d1: None | 'load' | 'all' -> D1's rule (bidir 300 us after station, then one-way)."""
    s = {}
    for g in GAPS:
        segs = []
        for (t0, t1) in windows_abs(g, cfg.ncyc):
            mode = load_mode if g in LOAD else base_mode(g, cfg.bracket)
            if d1 == "all" or (d1 == "load" and g in LOAD):
                segs += [(t0, t0 + D1_BIDIR, "bi", EDGE_IGN), (t0 + D1_BIDIR, t1, "f", EDGE_D1)]
            else:
                segs.append((t0, t1, mode, EDGE_IGN))
        s[g] = segs
    return s


def _zeros(t, i, t0, t1, eps):
    """Sign-change instants of i on (t0, t1] ignoring |i| < eps (linear interpolation)."""
    k0, k1 = np.searchsorted(t, t0), np.searchsorted(t, t1)
    tt, ii = t[k0:k1], i[k0:k1]
    s = np.sign(np.where(np.abs(ii) < eps, 0.0, ii))
    zs = []
    last = 0.0; lastk = None
    for k in range(len(ii)):
        if s[k] == 0:
            continue
        if last != 0 and s[k] != last:
            j = lastk
            # interpolate between the last nonzero-signed sample and this one
            ta, tb, ia, ib = tt[j], tt[k], ii[j], ii[k]
            zs.append(ta + (tb - ta) * ia / (ia - ib))
        last = s[k]; lastk = k
    return zs


def derive_event(t, i, v, t_ign, t_end, model, h, t_rec, holdoff, rec):
    """Derive the segment list for one load gap from t_ign to t_end from traces (t, i, v).
    Returns segs and appends event records to rec."""
    segs = []
    Vf = float(np.interp(t_ign, t, v))
    ein = EDGE_IGN if not rec else EDGE_SW
    imax = float(np.max(np.abs(i[np.searchsorted(t, t_ign):np.searchsorted(t, t_end)]))) \
        if np.searchsorted(t, t_end) > np.searchsorted(t, t_ign) else 0.0
    zs = [z for z in _zeros(t, i, t_ign, t_end, 1e-9 * max(imax, 1e-300)) if z < t_end]
    bounds = [t_ign] + zs
    half = []
    for k in range(len(zs)):
        a, b = bounds[k], bounds[k + 1]
        if k == 0:
            a = min(a + T_SPIKE, b)                          # ring peak, not the stray-dump spike
        ka, kb = np.searchsorted(t, a), max(np.searchsorted(t, b), np.searchsorted(t, a) + 1)
        seg = i[ka:kb]
        kp = int(np.argmax(np.abs(seg))) if len(seg) else 0
        half.append(dict(a=a, b=b, pk=float(abs(seg[kp])) if len(seg) else 0.0,
                         sgn=float(np.sign(seg[kp])) if len(seg) else 0.0,
                         tpk=float(t[ka + kp]) if len(seg) else a))
    ev = dict(t_ign=t_ign, Vf=Vf, n_half=len(half), p1=half[0]["pk"] if half else imax,
              p1_full=imax if not zs else float(np.max(np.abs(i[np.searchsorted(t, t_ign):np.searchsorted(t, zs[0])]))))
    rec.append(ev)
    if not half:                                             # no ring (G twins): arc held
        segs.append((t_ign, t_end, "bi", ein)); ev["ext"] = None
        i_end = float(np.interp(t_end, t, i)); ref = max(ev.get("p1_full") or 0.0, imax, 1e-300)
        if abs(i_end) > 1e-3 * ref:                          # window closes on current: next zero
            zs2 = _zeros(t, i, t_end, min(t_end + 2e-3, t[-1]), 1e-12 * max(abs(i_end), 1e-300))
            t_z = zs2[0] if zs2 else min(t_end + 2e-3, t[-1])
            segs.append((t_end, t_z + EDGE_SW, "f" if i_end > 0 else "r", EDGE_SW))
            ev["closing_zero"] = t_z; ev["i_at_end"] = 0.0
        else:
            ev["i_at_end"] = abs(i_end)
        return segs
    p1 = half[0]["pk"]
    # choose the extinguishing half-cycle
    kx = None
    if h is not None and h <= 0:
        h = H_TO_ZERO
    if h is not None and h > 0:
        for k, hc in enumerate(half):
            if hc["pk"] < h * p1:
                kx = k; break
    if kx is None:                                           # not met in the window: arc held
        segs.append((t_ign, t_end, "bi", ein)); ev["ext"] = None
        # the electrodes part at t_end: the arc goes out at its NEXT natural current zero
        # (rectifier of the current's sign from t_end), never by a chop (H2)
        i_end = float(np.interp(t_end, t, i))
        if abs(i_end) > 1e-3 * max(ev.get("p1_full") or 0.0, ev["p1"] or 0.0, 1e-300):
            zs2 = _zeros(t, i, t_end, min(t_end + 2e-3, t[-1]), 1e-12 * max(abs(i_end), 1e-300))
            t_z = zs2[0] if zs2 else min(t_end + 2e-3, t[-1])
            segs.append((t_end, t_z + EDGE_SW, "f" if i_end > 0 else "r", EDGE_SW))
            ev["closing_zero"] = t_z
        ev["i_at_end"] = 0.0 if abs(i_end) > 1e-3 * max(ev.get("p1_full") or 0.0, ev["p1"] or 0.0, 1e-300) \
            else abs(i_end)
        return segs
    hc = half[kx]
    mode_x = "f" if hc["sgn"] > 0 else "r"
    segs.append((t_ign, hc["tpk"], "bi", ein))
    segs.append((hc["tpk"], hc["b"], mode_x, EDGE_SW))
    t_ext = hc["b"]
    ev.update(ext=t_ext, k_ext=kx, sgn_ext=hc["sgn"], i_at_ext=float(abs(np.interp(t_ext, t, i))))
    if model == "RD" or holdoff <= 0:
        # afterwards: the established forward rectifier
        if mode_x == "f":
            segs[-1] = (hc["tpk"], t_end, "f", EDGE_SW)
        else:
            segs.append((t_ext, t_end, "f", EDGE_SW))
        return segs
    # M-SR holdoff: off, re-ignite in either direction if |v| > rho |Vf|
    t_h1 = min(t_ext + holdoff, t_end)
    k0, k1 = np.searchsorted(t, t_ext), np.searchsorted(t, t_h1)
    tt, vv = t[k0:k1], v[k0:k1]
    rho = np.ones_like(tt) if t_rec <= 0 else 1.0 - np.exp(-(tt - t_ext) / t_rec)
    hit = np.where(np.abs(vv) > rho * abs(Vf))[0]
    # ignore the first 20 ns (the zero itself / the 10 ns mode edge)
    hit = [k for k in hit if tt[k] > t_ext + 2 * EDGE_SW]
    if hit:
        t_r = float(tt[hit[0]])
        segs.append((t_ext, t_r, "off", EDGE_SW))
        ev["reignite"] = t_r
        segs += derive_event(t, i, v, t_r, t_end, model, h, t_rec, holdoff, rec)
        return segs
    segs.append((t_ext, t_h1, "off", EDGE_SW))
    if t_h1 < t_end:
        segs.append((t_h1, t_end, "f", EDGE_SW))
    ev["reignite"] = None
    return segs


def derive_sched(res, cfg, model, h=None, t_rec=0.0, holdoff=HOLDOFF, bracket=None):
    """Full schedule for all gaps from the traces of `res` under the load-gap model."""
    d = res["d"]; t = d["time"]
    s = sched_static(cfg)
    events = {}
    for g in LOAD:
        a, b = _gap_nodes(g)
        i = d[f"i(v_s{g.lower()})"]
        v = (d[f"v({a})"] if a != "0" else 0 * t) - (d[f"v({b})"] if b != "0" else 0 * t)
        segs = []; rec = []
        for (t0, t1) in windows_abs(g, cfg.ncyc):
            if t0 > t[-1]:
                break
            segs += derive_event(t, i, v, t0, min(t1, t[-1]), model, h, t_rec, holdoff, rec)
        s[g] = segs
        events[g] = rec
    return s, events


def _gap_nodes(g):
    for comp, a, b in a1.edge_list():
        if comp == g:
            return a1._n(a, "collapsed"), a1._n(b, "collapsed")
    raise KeyError(g)


def _norm(s):
    return {g: sorted((round(a / 1e-9), round(b / 1e-9), m) for a, b, m, e in segs if m != "off")
            for g, segs in s.items()}


def fixed_point(cfg, model, h=None, t_rec=0.0, holdoff=HOLDOFF, maxit=10, tol_ns=30):
    """Iterate run -> derive -> run until the derived load-gap schedule reproduces itself."""
    if model in ("OW",):
        r = run(cfg, sched_static(cfg, "f")); r["iters"] = 1; r["events"] = {}
        return r
    sched = sched_static(cfg, "bi")                          # start: arc held all window
    hist = []
    for it in range(maxit):
        cfg.name = re.sub(r"_it\d+$", "", cfg.name) + f"_it{it}"
        r = run(cfg, sched)
        new, ev = derive_sched(r, cfg, model, h, t_rec, holdoff)
        same = _close(new, sched, tol_ns)
        hist.append(same)
        if same:
            r["iters"] = it + 1; r["events"] = ev; r["converged"] = True
            return r
        sched = new
        _rm_raw(cfg.name)                          # intermediate iteration trace no longer needed
    r["iters"] = maxit; r["events"] = ev; r["converged"] = False
    return r


def _rm_raw(name):
    p = os.path.join(RAW, f"{name}.raw")
    if os.path.exists(p):
        os.remove(p)


def _close(s1, s2, tol_ns):
    for g in LOAD:
        a = sorted(s1[g]); b = sorted(s2[g])
        if len(a) != len(b):
            return False
        for x, y in zip(a, b):
            if x[2] != y[2] or abs(x[0] - y[0]) > tol_ns * 1e-9 or abs(x[1] - y[1]) > tol_ns * 1e-9:
                return False
    return True


