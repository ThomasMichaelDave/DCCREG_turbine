#!/usr/bin/env python3
"""
sim/island_gapbracket.py — ISLAND-ASDRAWN Pass A': re-grade the island verdict under physical gap
commutation of the LOAD gaps (SG3a1/SG4a1).
=====================================================================================================
Consumer of the Pass A (r0.1) ngspice harness — at this head it lives at
`sim/island_asdrawn_r01_spice.py` (renamed from `sim/island_asdrawn.py` by the r0.2 commit; frozen).
Its deck builder, raw reader and ledger are imported read-only; ONLY the gap elements of the
generated deck are rewritten (as D1 did). New decks: `spice/ia2_*`.

Gap commutation as mode schedules (no ngspice state machine) [ME]:
  every gap = three parallel conductances behind its sense source — bidirectional (V/RON),
  forward rectifier and reverse rectifier (soft rect, RON) — enabled by PWL mode sources.
  bidirectional -> rectifier(sign of the current) inside a same-sign half-cycle is SEAMLESS (both
  conduct I = V/RON there), and the rectifier then extinguishes EXACTLY at its natural current
  zero: extinction is event-exact, never a chop (H2).
  A rule engine reads a run's traces and derives each load gap's schedule for the chosen model
  (M-OW / M-RD / M-SR / D1); the run is repeated until the schedule reproduces itself (fixed point).

Models (brief §2):
  M-OW  one-way (Pass A gap_oneway) — the asymmetric bound (a rectifier).
  M-RD  arc bidirectional from ignition until a half-cycle's current peak < I_hold (fraction h of
        the event's first half-cycle peak); extinction only at a current zero; afterwards the
        established forward rectifier. h -> 0: extinction at the last forward zero before the
        window ends (full ring-down, no chop).
  M-SR  as M-RD, plus a 10 us holdoff after each extinction: re-ignition in EITHER direction if
        |V_gap| > rho(t)|V_f|, rho = 1 - exp(-(t - t_ext)/t_rec) [IR]; afterwards forward rectifier.
  D1    (reproduction only) bidirectional for 300 us after the station, then one-way.
Tiers [OC]/[IR]/[RH]/[ME]. Pure EE firewall.
"""
