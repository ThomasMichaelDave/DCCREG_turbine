LEDGER_CYCLES = a1.LEDGER_CYCLES


def ledger(res, cyc):
    """Pass A ledger (frozen a1.ledger) + motor coil R dissipation. Returns the a1 dict plus the
    signed residual s = (W - dE - E_diss)/E_diss and the +5 % total-dissipation trip."""
    L = a1.ledger(res, cyc)
    d = res["d"]; t = d["time"]; sl = a1._seg(t, cyc * T, (cyc + 1) * T)
    e_m = 0.0
    for nm, R in res["meta"].get("motor_r", []):
        e_m += R * a1._trap(d[f"i(l_{nm.lower()})"][sl] ** 2, t[sl])
    L["diss"]["motor_R"] = e_m
    Ed = L["E_diss"] + e_m
    s = (L["W"] - L["dE"] - Ed) / Ed
    s5 = (L["W"] - L["dE"] - 1.05 * Ed) / Ed
    Eg = L["E_gap"]
    return dict(W=L["W"], dE=L["dE"], E_diss=Ed, E_gap=Eg, diss=L["diss"], eta=L["dE"] / L["W"],
                resid=abs(s), resid_gap=abs(L["W"] - L["dE"] - Ed) / Eg, signed=s, trip_shift=s5 - s)


def summarize(res):
    d = res["d"]; t = d["time"]; c = res["cfg"]
    ncomp = int(t[-1] / T + 1e-9)
    cyc = [k for k in LEDGER_CYCLES if k + 1 <= ncomp]
    if not cyc:
        raise RuntimeError(f"{c.name}: ngspice stopped after {t[-1] / T:.2f} cycles (clean={res.get('ok')})")
    leds = [ledger(res, k) for k in cyc]
    W = [L["W"] for L in leds]
    out = dict(name=c.name, lx=c.lx, bracket=c.bracket, stray=c.stray_ref, motor=c.motor,
               reltol=c.reltol, cycles=ncomp, clean=res.get("ok"), iters=res.get("iters"),
               converged=res.get("converged", True),
               z=a1.z_of(t, d["v(1)"], d["v(4)"]), eta=float(np.mean([L["eta"] for L in leds])),
               resid=max(L["resid"] for L in leds), resid_gap=max(L["resid_gap"] for L in leds),
               trip_shift=float(np.mean([L["trip_shift"] for L in leds])),
               T_load=float(np.mean([(L["diss"].get("SG3a1", 0) + L["diss"].get("SG4a1", 0)) / L["W"] for L in leds])),
               T_esr=float(np.mean([sum(v for k, v in L["diss"].items() if k.endswith("esr")) / L["W"] for L in leds])),
               T_motor=float(np.mean([L["diss"].get("motor_R", 0) / L["W"] for L in leds])))
    res["leds"] = leds
    return out


def trv_record(res, cyc_list=(8, 9, 10)):
    """H4: per load event, reverse peak |V_gap| after extinction / |V_f| and its delay."""
    d = res["d"]; t = d["time"]; rows = []
    for g in LOAD:
        a, b = _gap_nodes(g)
        i = d[f"i(v_s{g.lower()})"]
        v = (d[f"v({a})"] if a != "0" else 0 * t) - (d[f"v({b})"] if b != "0" else 0 * t)
        for c in cyc_list:
            t0, t1 = windows_abs(g, c + 1)[c]
            if t1 > t[-1]:
                continue
            evs = (res.get("events") or {}).get(g)
            ext = None
            if evs:
                cand = [e for e in evs if t0 - 1e-12 <= e["t_ign"] <= t1 and e.get("ext")]
                ext = cand[-1]["ext"] if cand else None
                Vf = cand[-1]["Vf"] if cand else float(np.interp(t0, t, v))
                p1 = cand[-1]["p1"] if cand else None
            if ext is None:                                   # M-OW: first current zero
                k0, k1 = np.searchsorted(t, t0), np.searchsorted(t, t1)
                ii = i[k0:k1]; kp = int(np.argmax(np.abs(ii))); p1 = float(abs(ii[kp]))
                zz = np.where(np.abs(ii[kp:]) < 1e-3 * p1)[0]
                if not len(zz):
                    continue
                ext = float(t[k0 + kp + zz[0]]); Vf = float(np.interp(t0, t, v))
            k0, k1 = np.searchsorted(t, ext), np.searchsorted(t, ext + 3e-6)
            kr = k0 + int(np.argmax(np.abs(v[k0:k1])))
            rows.append(dict(gap=g, cycle=c, Vf=Vf, t_ext_us=(ext - t0) * 1e6,
                             i_ext_over_p1=float(abs(np.interp(ext, t, i)) / p1) if p1 else None,
                             trv_ratio=float(v[kr] / Vf), trv_delay_us=float((t[kr] - ext) * 1e6)))
    return rows


def _selftest():
    ok = True
    # a seamless bi->f hand-off: PWL values sum to 1 through the edge
    segs = [(1e-6, 2e-6, "bi", EDGE_IGN), (2e-6, 3e-6, "f", EDGE_SW)]
    pw = seg_pwl(segs, 1)
    def val(s, tt):
        body = s.replace("PWL(", " ").replace(")", " ").replace("\n+ ", " ")
        nums = [float(x) for x in body.split()]
        ts, vs = nums[0::2], nums[1::2]
        return float(np.interp(tt, ts, vs))
    for tt in (2.0e-6, 2.005e-6, 2.01e-6):
        ok &= abs(val(pw["bi"], tt) + val(pw["f"], tt) - 1.0) < 1e-9
    # zero finder on a damped sine
    tt = np.linspace(0, 10e-6, 20001); ii = np.exp(-tt / 20e-6) * np.sin(2 * np.pi * tt / 1.38e-6)
    zs = _zeros(tt, ii, 1e-9, 5e-6, 1e-12)
    ok &= abs(zs[0] - 0.69e-6) < 2e-9
    ok &= set(GAPS) == set(a1.WINDOWS) and set(LOAD) <= set(GAPS)
    if not ok:
        raise AssertionError("island_gapbracket on-load self-test FAILED")
    return ok


