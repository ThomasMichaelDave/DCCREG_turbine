def _pwl_points(segs, ncyc, m):
    s = seg_pwl(segs, ncyc)[m]
    body = s.replace("PWL(", " ").replace(")", " ").replace("\n+ ", " ")
    nums = [float(x) for x in body.split()]
    return np.array(nums[0::2]), np.array(nums[1::2])


def event_engine(res, g, t_ign, span=3e-6):
    """Integrate the frozen-C network from the ngspice pre-state at t_ign with scipy Radau.
    Gap conductances follow the SAME mode schedule. Returns t, V (nodes), I_L, i_gap(g)."""
    from scipy.integrate import solve_ivp
    d, m, cfg = res["d"], res["meta"], res["cfg"]
    nodes = m["nodes"]; ix = {n: k for k, n in enumerate(nodes)}; N = len(nodes)
    K = np.zeros((N, N))

    def addc(a, b, C):
        ia = ix.get(a); ib = ix.get(b)
        if ia is not None: K[ia, ia] += C
        if ib is not None: K[ib, ib] += C
        if ia is not None and ib is not None:
            K[ia, ib] -= C; K[ib, ia] -= C
    for nm, a, b, C in m["caps"]:
        addc(a, b, C)
    for nm, a, b, kind in m["varcaps"]:
        addc(a, b, float(a1._c_of_t(kind, np.array([t_ign]))[0]))
    Ki = np.linalg.inv(K)
    t = d["time"]
    V0 = np.array([np.interp(t_ign, t, d[f"v({n})"]) for n in nodes])
    inds = [x for x in m["inds"] if x[3] > 0]
    Rm = dict(m.get("motor_r", []))
    Rs = []
    for nm, a, b, Lv in inds:
        Rs.append(cfg.rlx if nm in ("Lx3", "Lx4") and cfg.rlx > 0 else Rm.get(nm, 0.0))
    I0 = np.array([np.interp(t_ign, t, d[f"i(l_{nm.lower()})"]) for nm, a, b, Lv in inds])
    Lv_ = np.array([x[3] for x in inds]); Rs = np.array(Rs)
    gaps = m["gaps"]
    modes = {}
    for gg, a, b in gaps:
        modes[gg] = {mm: _pwl_points(res["sched"][gg], cfg.ncyc, mm) for mm in ("bi", "f", "r")}
    RON, ROFF, VE = a1.GAP_RON, a1.GAP_ROFF, a1.VE_RECT

    def vab(V, a, b):
        return (V[ix[a]] if a in ix else 0.0) - (V[ix[b]] if b in ix else 0.0)

    def gap_i(gg, a, b, V, tt):
        x = vab(V, a, b); md = modes[gg]
        bi = np.interp(tt, *md["bi"]); f = np.interp(tt, *md["f"]); r = np.interp(tt, *md["r"])
        s = math.sqrt(x * x + VE * VE)
        return bi * x / RON + f / RON * 0.5 * (x + s) + r / RON * 0.5 * (x - s) + x / ROFF

    def rhs(tt, y):
        V = y[:N]; I = y[N:]
        inj = np.zeros(N)
        for gg, a, b in gaps:
            ig = gap_i(gg, a, b, V, tt)
            if a in ix: inj[ix[a]] -= ig
            if b in ix: inj[ix[b]] += ig
        dI = np.zeros(len(inds))
        for k, (nm, a, b, Lx) in enumerate(inds):
            if a in ix: inj[ix[a]] -= I[k]
            if b in ix: inj[ix[b]] += I[k]
            dI[k] = (vab(V, a, b) - Rs[k] * I[k]) / Lx
        return np.concatenate([Ki @ inj, dI])
    sol = solve_ivp(rhs, (t_ign, t_ign + span), np.concatenate([V0, I0]), method="Radau",
                    rtol=1e-9, atol=1e-12 * max(1.0, float(np.max(np.abs(V0)))), dense_output=True,
                    max_step=2e-9)
    tt = sol.t; Y = sol.y
    a, b = _gap_nodes(g)
    ig = np.array([gap_i(g, a, b, Y[:N, k], tt[k]) for k in range(len(tt))])
    return dict(t=tt, V=Y[:N], I=Y[N:], ig=ig, nodes=nodes, ix=ix, K=K, inds=inds, Rs=Rs,
                gaps=gaps, gap_i=gap_i)


def event_metrics_engine(E, g, t_ign):
    t, ig = E["t"], E["ig"]; a, b = _gap_nodes(g); ix = E["ix"]
    v = (E["V"][ix[a]] if a in ix else 0) - (E["V"][ix[b]] if b in ix else 0)
    return _event_metrics(t, ig, v, t_ign, E=E)


def event_metrics_spice(res, g, t_ign, span=3e-6):
    d = res["d"]; t = d["time"]; k0, k1 = np.searchsorted(t, t_ign), np.searchsorted(t, t_ign + span)
    a, b = _gap_nodes(g)
    v = (d[f"v({a})"] if a != "0" else 0 * t) - (d[f"v({b})"] if b != "0" else 0 * t)
    return _event_metrics(t[k0:k1], d[f"i(v_s{g.lower()})"][k0:k1], v[k0:k1], t_ign, res=res,
                          sl=(k0, k1))


def _event_metrics(t, ig, v, t_ign, E=None, res=None, sl=None):
    """t1/2 (ignition -> first current zero), TRV ratio (reverse peak / V_f), node-3 cap charge
    partition over [t_ign, zero], gap + ESR dissipation over the span."""
    Vf = float(v[0]); kp = int(np.argmax(np.abs(ig))); p1 = float(abs(ig[kp]))
    zz = [k for k in range(kp, len(ig) - 1) if ig[k] * ig[k + 1] <= 0]
    if not zz:
        return None
    k = zz[0]; tz = t[k] + (t[k + 1] - t[k]) * ig[k] / (ig[k] - ig[k + 1])
    kz = k
    kr = kz + int(np.argmax(np.abs(v[kz:])))
    out = dict(t_half_us=(tz - t_ign) * 1e6, trv_ratio=float(v[kr] / Vf), i_pk=p1, Vf=Vf)
    # node-3 partner charges (caps attached to node 3) at the zero
    if E is not None:
        V = E["V"]; ix = E["ix"]; K = E["K"]
        dq = K @ (np.array([np.interp(tz, t, V[j]) for j in range(len(ix))]) - V[:, 0])
        out["dq3"] = float(dq[ix["3"]])
        # dissipation: gaps + series R over the span
        pg = np.zeros(len(t))
        for gg, a, b in E["gaps"]:
            x = np.array([(V[ix[a], j] if a in ix else 0) - (V[ix[b], j] if b in ix else 0) for j in range(len(t))])
            ii = np.array([E["gap_i"](gg, a, b, V[:, j], t[j]) for j in range(len(t))])
            pg += x * ii
        pr = np.sum(E["Rs"][:, None] * E["I"] ** 2, axis=0)
        out["E_diss"] = float(np.trapezoid(pg + pr, t))
    if res is not None:
        d = res["d"]; m = res["meta"]; k0, k1 = sl; tt = d["time"][k0:k1]
        nodes = m["nodes"]
        V = np.array([d[f"v({n})"][k0:k1] for n in nodes])
        ix = {n: j for j, n in enumerate(nodes)}; N = len(nodes)
        K = np.zeros((N, N))
        for nm, a, b, C in m["caps"]:
            ia, ib = ix.get(a), ix.get(b)
            if ia is not None: K[ia, ia] += C
            if ib is not None: K[ib, ib] += C
            if ia is not None and ib is not None: K[ia, ib] -= C; K[ib, ia] -= C
        for nm, a, b, kind in m["varcaps"]:
            C = float(a1._c_of_t(kind, np.array([t_ign]))[0]); ia, ib = ix.get(a), ix.get(b)
            if ia is not None: K[ia, ia] += C
            if ib is not None: K[ib, ib] += C
            if ia is not None and ib is not None: K[ia, ib] -= C; K[ib, ia] -= C
        dq = K @ (np.array([np.interp(tz, tt, V[j]) for j in range(N)]) - V[:, 0])
        out["dq3"] = float(dq[ix["3"]])
        pg = np.zeros(len(tt))
        for gg, a, b in m["gaps"]:
            x = (d[f"v({a})"][k0:k1] if a != "0" else 0) - (d[f"v({b})"][k0:k1] if b != "0" else 0)
            pg += x * d[f"i(v_s{gg.lower()})"][k0:k1]
        pr = np.zeros(len(tt))
        for nm, a, b, Lv in m["inds"]:
            if nm in ("Lx3", "Lx4") and Lv > 0 and res["cfg"].rlx > 0:
                pr += res["cfg"].rlx * d[f"i(l_{nm.lower()})"][k0:k1] ** 2
        for nm, R in m.get("motor_r", []):
            pr += R * d[f"i(l_{nm.lower()})"][k0:k1] ** 2
        out["E_diss"] = float(np.trapezoid(pg + pr, tt))
    return out


def h5_events(res, g="SG3a1", cycles=(8, 9, 10), span=3e-6):
    """H5: >= 3 load events: engine vs ngspice within 1 % on t1/2, dq3, E_diss, TRV ratio."""
    rows = []
    for c in cycles:
        t_ign = windows_abs(g, c + 1)[c][0]
        E = event_engine(res, g, t_ign, span)
        me = event_metrics_engine(E, g, t_ign); ms = event_metrics_spice(res, g, t_ign, span)
        if me is None or ms is None:
            rows.append(dict(cycle=c, ok=False)); continue
        rel = {k: abs(me[k] - ms[k]) / max(abs(ms[k]), 1e-300) for k in ("t_half_us", "dq3", "E_diss", "trv_ratio")}
        rows.append(dict(cycle=c, engine=me, spice=ms, rel=rel, ok=all(v <= 0.01 for v in rel.values())))
    return all(r["ok"] for r in rows), rows


