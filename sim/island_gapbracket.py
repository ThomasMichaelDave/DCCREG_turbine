def write_gap_sub():
    txt = f"""* ia2_gap.sub — mode-scheduled gap (ISLAND-ASDRAWN Pass A'; generated by sim/island_gapbracket.py)
* bi/f/r = PWL mode sources (0..1): bidirectional arc, forward rectifier, reverse rectifier.
* Same RON / VE / ROFF as Pass A's sparkgap_bidir / gap_oneway (a1.GAP_RON, a1.VE_RECT, a1.GAP_ROFF).
.subckt ia2_gap a b bi f r PARAMS: RON={a1.GAP_RON} ROFF={a1.GAP_ROFF:.0e} VE={a1.VE_RECT}
  Bg a b I='V(bi)*V(a,b)/RON + V(f)/RON*0.5*(V(a,b)+sqrt(V(a,b)*V(a,b)+VE*VE)) + V(r)/RON*0.5*(V(a,b)-sqrt(V(a,b)*V(a,b)+VE*VE)) + V(a,b)/ROFF'
.ends ia2_gap
"""
    open(os.path.join(SPICE, "ia2_gap.sub"), "w").write(txt)


def seg_pwl(segs, ncyc):
    """Mode segments [(t0, t1, mode, edge_in)] -> three PWL strings (bi, f, r). A segment's mode
    ramps in over edge_in starting at t0; the last segment of a window ramps out over EDGE_IGN at
    its t1 unless the next segment starts there."""
    out = {}
    for m in ("bi", "f", "r"):
        pts = [(0.0, 0.0)]
        cur = 0.0
        segs_s = sorted(segs, key=lambda x: x[0])
        for k, (t0, t1, mode, ein) in enumerate(segs_s):
            val = 1.0 if mode == m else 0.0
            if val != cur:
                pts.append((t0, cur)); pts.append((t0 + ein, val)); cur = val
            nxt = segs_s[k + 1][0] if k + 1 < len(segs_s) else None
            if nxt is None or nxt > t1 + 1e-12:
                if cur != 0.0:
                    pts.append((t1, cur)); pts.append((t1 + EDGE_IGN, 0.0)); cur = 0.0
        pts.append((ncyc * T + 1e-3, cur))
        # times rounded exactly as Pass A's PWLs ({:.9e}): coincident stations must produce the
        # SAME breakpoint, else ngspice is forced through a 1e-14 s step mid-dump [ME]
        clean = []
        for tt, vv in pts:
            tt = float(f"{tt:.9e}")
            if clean and tt <= clean[-1][0]:
                tt = float(f"{clean[-1][0] + 1e-12:.9e}")
            clean.append((tt, vv))
        body = " ".join(f"{tt:.9e} {vv:g}" for tt, vv in clean)
        chunks = body.split(" ")
        lines = [" ".join(chunks[i:i + 16]) for i in range(0, len(chunks), 16)]
        out[m] = "PWL(" + "\n+ ".join(lines) + ")"
    return out


def build(cfg, sched, motor_r=True):
    """Pass A deck for cfg (a1.build, untouched) with gap lines rewritten per `sched`
    {gap: segments} and (motor in) R_COIL in series with each motor coil."""
    deck, meta = a1.build(cfg)
    L = deck.splitlines()
    out = []
    for ln in L:
        m = re.match(r"^X(\w+) (s_\w+) (\S+) arm_\w+ (sparkgap_bidir|gap_oneway)$", ln)
        if m and m.group(1) in GAPS:
            g = m.group(1)
            out.append(f"X{g} {m.group(2)} {m.group(3)} mbi_{g.lower()} mf_{g.lower()} mr_{g.lower()} ia2_gap")
            pw = seg_pwl(sched[g], cfg.ncyc)
            for mm in ("bi", "f", "r"):
                out.append(f"V_m{mm}_{g.lower()} m{mm}_{g.lower()} 0 {pw[mm]}")
            continue
        m = re.match(r"^L_(L_[AB]\d) (\S+) (\S+) (\S+)$", ln)
        if m and motor_r and cfg.motor:
            nm, a, b, Lv = m.groups()
            out.append(f"L_{nm} {a} x_{nm.lower()} {Lv}")
            out.append(f"R_{nm}coil x_{nm.lower()} {b} {R_COIL:g}")
            continue
        if ln.startswith(".include sparkgap_bidir.sub"):
            out.append(ln); out.append(".include ia2_gap.sub"); continue
        out.append(ln)
    meta = dict(meta)
    if cfg.motor and motor_r:
        meta["motor_r"] = [(nm, R_COIL) for nm, a, b, Lv in meta["inds"] if nm.startswith("L_")]
    return "\n".join(out) + "\n", meta


def run(cfg, sched, motor_r=True):
    write_gap_sub()
    deck, meta = build(cfg, sched, motor_r)
    open(os.path.join(SPICE, f"{cfg.name}.cir"), "w").write(deck)
    r = subprocess.run(["ngspice", "-b", f"{cfg.name}.cir"], capture_output=True, text=True,
                       cwd=SPICE, timeout=7200)
    log = r.stdout + r.stderr
    ok = ("too small" not in log) and ("aborted" not in log.lower())
    d = a1.read_raw(os.path.join(RAW, f"{cfg.name}.raw"))
    return dict(cfg=cfg, meta=meta, d=d, ok=ok, sched=sched)


