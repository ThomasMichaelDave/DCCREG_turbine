def admissibility(res, cycles=(8, 9, 10)):
    """Largest |V_gap| the load gap BLOCKS (outside its conducting intervals) after its first
    extinction, over the rest of its window, / |V_f| of the event that preceded it. A symmetric
    self-break gap can hold at most |V_f| (rho_max = 1); > 1 means the model relied on a rectifier."""
    d = res["d"]; t = d["time"]; out = []
    for g in LOAD:
        a, b = _gap_nodes(g)
        v = (d[f"v({a})"] if a != "0" else 0 * t) - (d[f"v({b})"] if b != "0" else 0 * t)
        segs = res["sched"][g]
        for c in cycles:
            t0, t1 = windows_abs(g, c + 1)[c]
            k0, k1 = np.searchsorted(t, t0), np.searchsorted(t, t1)
            tt, vv = t[k0:k1], v[k0:k1]
            cond = np.zeros(len(tt), bool)
            for s0, s1, m, e in segs:
                if m == "bi" and s1 > t0 and s0 < t1:
                    cond |= (tt >= s0) & (tt <= s1 + EDGE_SW)
                if m in ("f", "r") and s1 > t0 and s0 < t1:
                    sgn = 1 if m == "f" else -1
                    cond |= (tt >= s0) & (tt <= s1) & (sgn * vv > 0)
            Vf = float(np.interp(t0, t, v))
            first_off = np.where(~cond & (tt > t0 + 0.2e-6))[0]
            if not len(first_off):
                out.append(dict(gap=g, cycle=c, blocked_over_Vf=0.0)); continue
            kb = first_off
            j = kb[int(np.argmax(np.abs(vv[kb])))]
            out.append(dict(gap=g, cycle=c, blocked_over_Vf=float(abs(vv[j]) / abs(Vf)),
                            polarity=("reverse" if np.sign(vv[j]) != np.sign(Vf) else "forward"),
                            at_us=float((tt[j] - t0) * 1e6)))
    return out


def admissibility_events(res, cycles=(8, 9, 10)):
    """Per holdoff ('off' segment) of the load gap: max |V_gap| / |V_f| of the event that preceded
    it (the M-SR rule's own reference), plus the reverse |V| held by the post-holdoff forward
    rectifier / that V_f. rho_max = 1: a value > 1 would be a rectifier."""
    d = res["d"]; t = d["time"]; out = []
    for g in LOAD:
        a, b = _gap_nodes(g)
        v = (d[f"v({a})"] if a != "0" else 0 * t) - (d[f"v({b})"] if b != "0" else 0 * t)
        segs = sorted(res["sched"][g])
        for c in cycles:
            t0, t1 = windows_abs(g, c + 1)[c]
            Vf = None; worst_off = 0.0; worst_rect = 0.0
            for s0, s1, m, e in segs:
                if s1 < t0 or s0 > t1:
                    continue
                if m == "bi":
                    Vf = float(np.interp(s0, t, v))
                k0, k1 = np.searchsorted(t, s0 + 2 * EDGE_SW), np.searchsorted(t, s1)
                if k1 <= k0 or Vf is None:
                    continue
                seg = v[k0:k1]
                if m == "off":
                    worst_off = max(worst_off, float(np.max(np.abs(seg)) / abs(Vf)))
                if m == "f":
                    worst_rect = max(worst_rect, float(np.max(np.clip(-seg, 0, None)) / abs(Vf)))
            out.append(dict(gap=g, cycle=c, holdoff_max_over_Vf_event=worst_off,
                            rect_reverse_over_Vf_event=worst_rect))
    return out
