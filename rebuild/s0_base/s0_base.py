"""rebuild/s0_base/s0_base.py -- Stage 0 of the rebuild: the base schematic, de Queiroz's Fig. 1 (the symmetrical
unipolar variable-capacitance generator), as the doubler's first schematic.

Source [OC]: docs/reference/deQueiroz-2019-analysis-electronic-electrostatic-generators.pdf, Fig. 1 and §III.
The designer (2026-10-14): "this paper's fig. 1 schematic is the new first schematic to create the doubler from".

TOPOLOGY below is the single source of the base schematic: the netlist written here and the drawing
(make_schematic.py) are both generated from it.

Records (the designer, 2026-10-14: keep ideal and real diode records):
  - ideal: the charge-conservation LCP solver of sim/queiroz_matrix.py (exact ideal diodes; z and the eigenvector);
  - ngspice, near-ideal diodes (the repo's ND law, n 0.005), the deck s0_base.cir written by this script;
  - real diodes: deferred to Stage 1, where the values are the tube's (at the paper's 150 V scale an HV stick's
    leakage model says nothing about the tube) [IR].
Values are the paper's example (C1, C2 60-360 pF complementary, Ca = Cb = 330 pF, 20 Hz) [OC]; Stage 1 sizes them.

Writes rebuild/s0_base/s0_base.cir and rebuild/s0_base/s0_base_results.json.
Usage: python3 rebuild/s0_base/s0_base.py
"""
import json
import math
import os
import subprocess
import sys
import tempfile

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "sim"))
import queiroz_matrix as qm  # noqa: E402  the ideal solver (sim/queiroz_matrix.py)

# ---------------------------------------------------------------------------------------------------------------------
# The base schematic [OC: the PDF, Fig. 1, as printed: positive polarity]. Nodes 1..4, 0 = REF.
# ---------------------------------------------------------------------------------------------------------------------
TOPOLOGY = dict(
    name="S0 base: de Queiroz Fig. 1, symmetrical unipolar generator",
    polarity="positive, as printed (all node voltages >= 0)",
    capacitors={
        "C1": dict(nodes=("1", "0"), kind="variable", role="varicap A; C_max at phase 1"),
        "C2": dict(nodes=("4", "0"), kind="variable", role="varicap B, antiphase to C1 (C1 + C2 constant)"),
        "Ca": dict(nodes=("1", "2"), kind="fixed", role="transfer capacitor A"),
        "Cb": dict(nodes=("3", "4"), kind="fixed", role="transfer capacitor B"),
    },
    diodes={                                       # (anode, cathode)
        "D1": ("0", "2"), "D2": ("0", "3"), "D3": ("3", "1"), "D4": ("2", "4"),
    },
)
# The paper's example values [OC: the PDF, §III]
VALUES = dict(Cmin=60e-12, Cmax=360e-12, Ca=330e-12, Cb=330e-12, F=20.0)
N_CYC = 16


def deck(v=VALUES, seed=1.0, n=0.005, n_cyc=N_CYC):
    """The ngspice deck from TOPOLOGY. Varicaps as charge sources Q = C(t) V, cosine in antiphase [IR: the waveform;
    the ideal z depends only on the extremes and C1 + C2 constant, OC]."""
    w = 2 * math.pi * v["F"]
    s1, s2 = f"(0.5*(1+cos({w:.8e}*time)))", f"(0.5*(1-cos({w:.8e}*time)))"
    sw = {"C1": s1, "C2": s2}
    t = ["* " + TOPOLOGY["name"] + " -- generated by rebuild/s0_base/s0_base.py from TOPOLOGY"]
    for k, c in TOPOLOGY["capacitors"].items():
        a, b = c["nodes"]
        if c["kind"] == "variable":
            t.append(f"{k}v {a} {b} Q='({v['Cmin']:.4e}+{v['Cmax'] - v['Cmin']:.4e}*{sw[k]})*V({a})'")
        else:
            t.append(f"{k} {a} {b} {v[k]:.4e}")
    t.append(f".model ND D(is=1e-12 n={n:g} rs=1e-3 cjo=0)")
    t += [f"{k} {a} {c} ND" for k, (a, c) in TOPOLOGY["diodes"].items()]
    ms = 1.0 / v["F"] / 4000
    # seed on the varicaps' nodes only: it excites the growing mode (sim/queiroz_matrix-findings.md, the caveat)
    t += [f".ic v(1)={seed} v(4)={seed} v(2)=0 v(3)=0", ".control", f"tran {ms:.4e} {n_cyc / v['F']:.6e} uic",
          "wrdata out.dat v(1) v(2) v(3) v(4)", ".endc",
          f".options reltol=1e-6 abstol=1e-15 vntol=1e-9 maxstep={ms:.4e} method=gear", ".end"]
    return "\n".join(t) + "\n"


def run_ngspice(txt, v=VALUES, n_cyc=N_CYC):
    with tempfile.TemporaryDirectory() as d:
        open(os.path.join(d, "x.cir"), "w").write(txt)
        subprocess.run(["ngspice", "-b", "x.cir"], capture_output=True, text=True, timeout=600, cwd=d)
        raw = np.loadtxt(os.path.join(d, "out.dat"))
    tt = raw[:, 0]
    V = raw[:, [1, 3, 5, 7]]
    cyc = np.floor(tt * v["F"]).astype(int)
    pk = [float(V[cyc == k, 0].max()) for k in range(n_cyc) if np.any(cyc == k)]
    z = [pk[k + 1] / pk[k] for k in range(len(pk) - 1)]
    k = n_cyc - 2                                  # phase 1 of the last full cycle: C1 at C_max (cos = 1)
    i1 = int(np.argmin(np.abs(tt - k / v["F"])))
    e = V[i1] / V[i1, 0]
    return dict(z_cycle=float(np.median(z[-5:])), z_history=z, V1_peaks=pk, e_phase1=e.tolist(),
                min_node_V=float(V.min()))


def main():
    v = VALUES
    al, be = v["Cmax"] / v["Cmin"], v["Ca"] / v["Cmin"]
    circ = qm.fig1(al, be)
    # the solver's circuit and TOPOLOGY must be the same circuit [OC check]
    assert [tuple(map(str, d)) for d in circ["diodes"]] == list(TOPOLOGY["diodes"].values())
    ideal = qm.power_iteration(circ, 8000)
    txt = deck()
    open(os.path.join(HERE, "s0_base.cir"), "w").write(txt)
    sp = run_ngspice(txt)
    e = ideal["e_phase1"]
    out = dict(
        topology=TOPOLOGY, values=v, alpha=al, beta=be,
        ideal=dict(solver="sim/queiroz_matrix.py (LCP, exact ideal diodes), 8000 steps a half cycle",
                   z_cycle=ideal["z_cycle"], sqrt_z_half_cycle=math.sqrt(ideal["z_cycle"]),
                   a_e21_e11=e[1], b_e41_e11=e[3], e_phase1=e),
        ngspice=dict(deck="rebuild/s0_base/s0_base.cir", diode="ND: is 1e-12, n 0.005, rs 1e-3 (near-ideal)", **sp),
        paper=dict(sqrt_z=1.17138, a=0.159674, b=2.24117,
                   note="the printed sqrt z is 1.6e-5 under the converged 1.171396 (sim/queiroz-matrix-findings.md)"),
        real_diodes="deferred to Stage 1 (tube values) [IR]",
    )
    out["agreement"] = dict(
        ngspice_vs_ideal_z=sp["z_cycle"] / ideal["z_cycle"] - 1,
        ngspice_vs_ideal_a=sp["e_phase1"][1] - e[1], ngspice_vs_ideal_b=sp["e_phase1"][3] - e[3],
        ideal_vs_paper_a=e[1] - 0.159674, ideal_vs_paper_b=e[3] - 2.24117)
    json.dump(out, open(os.path.join(HERE, "s0_base_results.json"), "w"), indent=1)
    print(f"ideal   z {ideal['z_cycle']:.6f}/cycle  sqrt {math.sqrt(ideal['z_cycle']):.6f}  a {e[1]:.6f}  b {e[3]:.5f}")
    print(f"ngspice z {sp['z_cycle']:.6f}/cycle  a {sp['e_phase1'][1]:.6f}  b {sp['e_phase1'][3]:.5f}  "
          f"min node {sp['min_node_V']:.3g} V")
    print("agreement", {k: f"{x:.2e}" for k, x in out["agreement"].items()})


if __name__ == "__main__":
    main()
